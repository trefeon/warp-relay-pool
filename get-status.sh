#!/bin/sh
# Print each relay's port, live egress IP, and tunnel URL (when tunnels
# exist), then the ready-to-paste client commands.
#
# Mesh direct ingress: host port 310N forwards to the relay app's container
# port 300N. The client lines use the router's actual host bind, parsed from
# the generated docker-compose.yml (the wizard sets INGRESS_BIND to the VPS
# Tailscale IP for mesh installs; the safe default bind is 127.0.0.1, which
# is not reachable from the tailnet and is reported as such). Quick-Tunnel
# `/freeflow add` lines print ONLY when tunnel containers exist (graceful
# when absent).
#
# Usage: ./get-status.sh [count]     (default COUNT env, else 10)
# Missing/stopped containers print "(not ready)" and never abort the table
# (safe under `set -e` callers too).
set -u

# Operate on the checkout this script lives in, not the caller's CWD.
POOL_DIR="${POOL_DIR:-$(cd "$(dirname "$0")" && pwd)}"
cd "$POOL_DIR" || exit 1

COUNT="${1:-${COUNT:-10}}"

case "$COUNT" in
  ''|*[!0-9]*)
    echo "error: count must be an integer 1..64, got '$COUNT'" >&2
    exit 1
    ;;
esac
if [ "$COUNT" -lt 1 ] || [ "$COUNT" -gt 64 ]; then
  echo "error: count must be an integer 1..64, got '$COUNT'" >&2
  exit 1
fi

# Host binds as generated by generate-compose.sh: SOCKS probes must dial the
# bind that actually listens (an interface-specific WARP_BIND has no loopback
# listener), and the mesh client lines must use the router bind. Defaults
# mirror the generator's loopback binds when no compose file exists.
SOCKS_BIND="$(sed -n 's/^ *- "\([^":]*\):[0-9][0-9]*:1080"$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"
[ -n "$SOCKS_BIND" ] || SOCKS_BIND="127.0.0.1"
ROUTER_PUBLISHED="$(sed -n 's/^ *- "\([^":]*\):3101-.*$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"
ROUTER_BIND="$ROUTER_PUBLISHED"
BASE_PORT="$(sed -n 's/^ *- BASE_PORT=\([0-9][0-9]*\)$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"
[ -n "$BASE_PORT" ] || BASE_PORT=3000

tunnel_url() {
  docker logs "warp-relay-tunnel-$1" 2>&1 \
    | grep -oE 'https://[a-zA-Z0-9.-]+\.trycloudflare\.com' \
    | tail -n 1 || true
}

egress_ip() {
  # 1. Fast host-side SOCKS5 probe (works for warp-lite and standard containers)
  socks_port=$((10800 + $1))
  ip="$(curl -s -m 4 -x "socks5h://${SOCKS_BIND}:${socks_port}" https://cloudflare.com/cdn-cgi/trace 2>/dev/null | sed -n 's/^ip=//p')"
  if [ -n "$ip" ]; then
    printf '%s' "$ip"
    return
  fi
  # 2. In-container docker exec fallback
  docker exec "warp-relay-warp-$1" curl -s -m 8 https://cloudflare.com/cdn-cgi/trace 2>/dev/null \
    | sed -n 's/^ip=//p' || true
}

mesh_ip() {
  if command -v tailscale >/dev/null 2>&1; then
    tailscale ip -4 2>/dev/null | head -n 1 || true
  fi
}

echo "=== WARP relay status (1..${COUNT}) ==="
printf "%-10s %-8s %-34s %s\n" "INSTANCE" "PORT" "EGRESS IP" "TUNNEL URL"
echo "--------------------------------------------------------------------------------------------"

SEEN_IPS=""
DUP_IPS=""
i=1
while [ "$i" -le "$COUNT" ]; do
  # The table must show what a client dials: the host-published 310N port in
  # mesh mode, or the in-network BASE_PORT+N when nothing is published.
  if [ -n "$ROUTER_PUBLISHED" ]; then
    PORT="$((3100 + i))"
    PORT_LABEL=":${PORT}"
  else
    PORT="$((BASE_PORT + i))"
    PORT_LABEL=":${PORT}*"
  fi

  URL="$(tunnel_url "$i")"
  [ -z "$URL" ] && URL="(none / mesh-VPN direct)"

  # Egress address is a property of the WARP client container, so read it there
  # rather than through the relay app.
  IP="$(egress_ip "$i")"
  [ -z "$IP" ] && IP="(not ready)"
  case "$IP" in
    "(not ready)"|"") ;;
    *)
      case " ${SEEN_IPS} " in
        *" ${IP} "*) DUP_IPS="${DUP_IPS} ${IP}" ;;
        *) SEEN_IPS="${SEEN_IPS} ${IP}" ;;
      esac
      ;;
  esac

  printf "%-10s %-9s %-34s %s\n" "warp-${i}" "$PORT_LABEL" "$IP" "$URL"
  i=$((i + 1))
done
if [ -n "$DUP_IPS" ]; then
  echo ""
  echo "note: relays share egress IP(s)${DUP_IPS} — expected on IPv4 (Cloudflare"
  echo "      WARP CGNAT); per-relay isolation is per-IPv6 egress address."
fi
if [ -z "$ROUTER_PUBLISHED" ]; then
  echo "* in-network relay port (tunnels mode publishes no host port)"
fi

# Keep-cold scheduler state (bounded, read-only). The prober writes
# RELAY_STATE_FILE; CI and fresh checkouts have neither node nor the file, and
# both cases must stay silent rather than fail the table above. Nothing here
# reads an egress address — the state holds relay indexes, models and
# timestamps only, and that is all this section may print.
STATE_FILE="${RELAY_STATE_FILE:-.keep-cold/state.json}"
if command -v node >/dev/null 2>&1 && [ -f "$STATE_FILE" ]; then
  STATE_FILE="$STATE_FILE" RELAY_COUNT="$COUNT" node -e '
const fs = require("fs");
let state;
try {
  state = JSON.parse(fs.readFileSync(process.env.STATE_FILE, "utf8"));
} catch (err) {
  process.exit(0);
}
const relays = state && typeof state === "object" ? state.relays : null;
if (!relays || typeof relays !== "object") process.exit(0);
const count = Number(process.env.RELAY_COUNT) || 0;
const nowSec = Date.now() / 1000;
const epochSec = function (value) {
  const n = Number(value);
  if (!Number.isFinite(n) || n <= 0) return 0;
  return n > 1e11 ? Math.round(n / 1000) : Math.round(n);
};
const rows = [];
const hourAgo = nowSec - 3600;
for (let i = 1; i <= count; i += 1) {
  const rec = relays[String(i)] || relays["warp-" + i];
  if (!rec || typeof rec !== "object") continue;
  const failures = Number(rec.consecutiveFailures) || 0;
  const until = epochSec(rec.cooldownUntil);
  const cooling = until > nowSec ? Math.round(until - nowSec) : 0;
  const dirty = rec.dirty === true || rec.dirty === "yes" || failures > 0;
  let hourly = 0;
  if (Array.isArray(rec.rotations)) {
    for (const ts of rec.rotations) {
      if (epochSec(ts) > hourAgo) hourly += 1;
    }
  }
  let model = "";
  if (rec.last429 && typeof rec.last429 === "object") {
    model = rec.last429.model ? String(rec.last429.model) : "";
  } else if (typeof rec.last429 === "string") {
    model = rec.last429;
  }
  rows.push(
    "  #" + i +
    " dirty=" + (dirty ? "yes" : "no") +
    " cooldown=" + cooling + "s" +
    " failures=" + failures +
    " rotations1h=" + hourly +
    (rec.pendingVerify === true ? " pending=yes" : "") +
    " last429=" + (model || "(none)")
  );
}
if (rows.length === 0) process.exit(0);
process.stdout.write("\n=== keep-cold scheduler (last known per-relay state) ===\n");
process.stdout.write(rows.join("\n") + "\n");
' 2>/dev/null || true
fi

TS_IP="$(mesh_ip)"
[ -z "$TS_IP" ] && TS_IP="<tailscale-ip>"

FOUND_TUNNELS=0
i=1
while [ "$i" -le "$COUNT" ]; do
  URL="$(tunnel_url "$i")"
  if [ -n "$URL" ]; then
    if [ "$FOUND_TUNNELS" -eq 0 ]; then
      echo ""
      echo "=== TryCloudflare Quick Tunnel commands (public HTTPS) ==="
    fi
    FOUND_TUNNELS=1
    echo "/freeflow add ${URL} relay-${i}"
  fi
  i=$((i + 1))
done

# Bind values were parsed at the top of the script. A wildcard router bind
# (0.0.0.0) is dialable from the tailnet, so print the tailnet address;
# loopback is not reachable from clients and gets a fix-up hint instead.
# (IPv6 binds are rejected by the generator, so ROUTER_BIND is always IPv4.)
if [ "$FOUND_TUNNELS" -eq 0 ]; then
  echo ""
  if [ -z "$ROUTER_BIND" ]; then
    echo "=== Mesh-VPN direct: relay router not host-published ==="
    echo "(generate a mesh-mode file: INGRESS_BIND=<tailscale-ip> ./generate-compose.sh ${COUNT})"
  elif [ "$ROUTER_BIND" = "127.0.0.1" ]; then
    echo "=== Mesh-VPN direct: router bound to 127.0.0.1 (not reachable from the tailnet) ==="
    echo "(re-run: INGRESS_BIND=${TS_IP} ./generate-compose.sh ${COUNT} && docker compose up -d)"
  elif [ "$ROUTER_BIND" = "0.0.0.0" ]; then
    echo "=== Mesh-VPN direct commands (router bound on all interfaces) ==="
    i=1
    while [ "$i" -le "$COUNT" ]; do
      TS_PORT=$((3100 + i))
      echo "/freeflow add http://${TS_IP}:${TS_PORT} relay-${i}"
      i=$((i + 1))
    done
  else
    echo "=== Mesh-VPN direct commands (Tailscale private) ==="
    i=1
    while [ "$i" -le "$COUNT" ]; do
      TS_PORT=$((3100 + i))
      echo "/freeflow add http://${ROUTER_BIND}:${TS_PORT} relay-${i}"
      i=$((i + 1))
    done
  fi
else
  echo ""
  echo "=== Mesh-VPN direct: not published in tunnels mode ==="
  echo "(mesh ingress needs a mesh-mode deployment: ./generate-compose.sh ${COUNT})"
fi
